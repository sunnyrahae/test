function nextQ(){
  if(answers[current]===null)return;
  if(current===questions.length-1){calcResult();return;}
  current++;renderQ();
}

function calcResult(){
  scores={};
  questions.forEach((q,qi)=>{
    const ai=answers[qi]; if(ai===null)return;
    const sc=q.opts[ai].score;
    for(const k in sc)scores[k]=(scores[k]||0)+sc[k];
  });
  showResult();
}

